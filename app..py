# PERHITUNGAN PONDASI TIANG
# ============================================================

def hitung_pondasi(data, diameter, kedalaman, fk):

    df = validasi_data(data)

    if len(df) < 2:
        raise ValueError("Data sondir belum mencukupi.")

    diameter = float(diameter)
    kedalaman = float(kedalaman)
    fk = float(fk)

    if diameter <= 0 or kedalaman <= 0 or fk <= 0:
        raise ValueError(
            "Semua parameter harus lebih dari nol."
        )

    kedalaman_maks = float(
        df["Kedalaman (m)"].max()
    )

    if kedalaman > kedalaman_maks:
        raise ValueError(
            "Kedalaman tiang melebihi kedalaman data sondir."
        )

    D = diameter * 100

    Ap = math.pi * D**2 / 4

    K = math.pi * D

    batas_atas = max(
        0,
        kedalaman - 8 * diameter
    )

    batas_bawah = min(
        kedalaman_maks,
        kedalaman + 4 * diameter
    )

    zona = df[
        (df["Kedalaman (m)"] >= batas_atas) &
        (df["Kedalaman (m)"] <= batas_bawah)
    ]

    if len(zona) > 0:

        qc_rata = float(
            zona["qc (kg/cm2)"].mean()
        )

    else:

        qc_rata = interpolasi_data(
            df,
            "qc (kg/cm2)",
            kedalaman
        )

    qb = min(
        0.4 * qc_rata,
        40.0
    )

    Qp = qb * Ap

    JHL_ujung = interpolasi_data(
        df,
        "JHL (kg/cm)",
        kedalaman
    )

    Qs = JHL_ujung * K

    Qu = Qp + Qs

    Qizin = Qu / fk

    konversi = 0.00980665

    return {

        "diameter": diameter,
        "kedalaman": kedalaman,
        "fk": fk,

        "Ap": Ap,
        "K": K,

        "qc_rata": qc_rata,
        "qb": qb,

        "JHL_ujung": JHL_ujung,

        "Qp": Qp,
        "Qs": Qs,
        "Qu": Qu,
        "Qizin": Qizin,

        "Qp_kN": Qp * konversi,
        "Qs_kN": Qs * konversi,
        "Qu_kN": Qu * konversi,
        "Qizin_kN": Qizin * konversi,

        "batas_atas": batas_atas,
        "batas_bawah": batas_bawah

    }

