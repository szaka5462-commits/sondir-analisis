def upload_data(file):

    if file is None:
        return None

    ekstensi = os.path.splitext(file.name)[1].lower()

    try:

        if ekstensi == ".csv":
            df = pd.read_csv(file)

        elif ekstensi in [".xlsx", ".xls"]:
            df = pd.read_excel(file)

        else:
            st.error("Format file tidak didukung.")
            return None

        df.columns = (
            df.columns.astype(str)
            .str.strip()
            .str.lower()
        )

        pemetaan = {

            "kedalaman": "Kedalaman (m)",
            "kedalaman (m)": "Kedalaman (m)",

            "qc": "qc (kg/cm2)",
            "qc (kg/cm2)": "qc (kg/cm2)",

            "jhl": "JHL (kg/cm)",
            "jhl (kg/cm)": "JHL (kg/cm)"

        }

        df = df.rename(columns=pemetaan)

        for kolom in KOLOM:

            if kolom not in df.columns:

                st.error(
                    f"Kolom {kolom} tidak ditemukan."
                )

                return None

        df = validasi_data(df)

        if len(df) < 2:

            st.error(
                "Data minimal harus memiliki 2 baris lengkap."
            )

            return None

        return df

    except Exception as e:

        st.error(f"Gagal membaca file: {e}")

        return None

