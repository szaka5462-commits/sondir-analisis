def analisis_dasar(data):

    df = validasi_data(data)

    if len(df) < 2:
        raise ValueError(
            "Masukkan minimal 2 baris data sondir lengkap."
        )

    jumlah = len(df)

    qc_min = df["qc (kg/cm2)"].min()
    qc_max = df["qc (kg/cm2)"].max()
    qc_rata = df["qc (kg/cm2)"].mean()

    jhl_min = df["JHL (kg/cm)"].min()
    jhl_max = df["JHL (kg/cm)"].max()

    kedalaman_maks = df["Kedalaman (m)"].max()

    hasil_tabel = df.copy()

    hasil_tabel["Interval Kedalaman (m)"] = (
        hasil_tabel["Kedalaman (m)"].diff()
    )

    hasil_tabel["Delta JHL (kg/cm)"] = (
        hasil_tabel["JHL (kg/cm)"].diff()
    )

    hasil_tabel["Hambatan Lekat Interval (kg/cm2)"] = (
        hasil_tabel["Delta JHL (kg/cm)"] /
        hasil_tabel["Interval Kedalaman (m)"]
    )

    hasil_tabel = hasil_tabel.replace(
        [np.inf, -np.inf],
        np.nan
    )

    ringkasan = {
        "jumlah_data": jumlah,
        "kedalaman_maks": kedalaman_maks,
        "qc_min": qc_min,
        "qc_max": qc_max,
        "qc_rata": qc_rata,
        "jhl_min": jhl_min,
        "jhl_max": jhl_max
    }

    return hasil_tabel, ringkasan

