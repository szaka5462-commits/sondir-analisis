def validasi_data(data):

    if data is None:
        return pd.DataFrame(columns=KOLOM)

    df = pd.DataFrame(data).copy()

    for kolom in KOLOM:
        if kolom not in df.columns:
            df[kolom] = np.nan

    for kolom in KOLOM:
        df[kolom] = pd.to_numeric(
            df[kolom],
            errors="coerce"
        )

    df = df[KOLOM]

    df = df.dropna(subset=KOLOM)

    df = df[
        (df["Kedalaman (m)"] >= 0) &
        (df["qc (kg/cm2)"] >= 0) &
        (df["JHL (kg/cm)"] >= 0)
    ]

    df = df.sort_values(
        "Kedalaman (m)"
    ).reset_index(drop=True)

    df = df.drop_duplicates(
        subset=["Kedalaman (m)"],
        keep="last"
    ).reset_index(drop=True)

    return df

